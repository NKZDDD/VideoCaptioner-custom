"""Opt-in, round-trip-safe line positioning on the existing ASS script canvas."""
import math
import re

PREFIX = '; VideoCaptionerLineGeometry: '
PATTERN = re.compile(r'^; VideoCaptionerLineGeometry: (Default|Secondary),baseline=([0-9.]+),pitch=([0-9.]+)$')
EVENT = re.compile(r'^VCLineV1:(\d+):(\d+)$')

def parse(style, height=720):
    result = {}
    for row in style.splitlines():
        if not row.startswith(PREFIX):
            continue
        match = PATTERN.fullmatch(row)
        if not match or match[1] in result:
            raise ValueError('字幕行距定位标记无效或重复')
        baseline, pitch = float(match[2]), float(match[3])
        if not all(math.isfinite(v) for v in (baseline, pitch)) or not 0 <= baseline <= height or not 0 < pitch <= height:
            raise ValueError('字幕行距定位超出画布范围')
        result[match[1]] = (baseline, pitch)
    return result

def fragments(text, geometry, width):
    """Keep the whole block centered on the calibrated single-line anchor."""
    prefix = ''
    while text.startswith('{') and '}' in text:
        end = text.index('}') + 1
        prefix += text[:end]
        text = text[end:]
    lines = text.replace(r'\N', '\n').split('\n')
    baseline, pitch = geometry
    for index, line in enumerate(lines):
        y = baseline + (index - (len(lines) - 1) / 2) * pitch
        anchor = r'{\an2\pos(' + f'{width/2:g},{y:g}' + ')}'
        yield index, len(lines), anchor + prefix + line

def restore(ass):
    """Collapse explicitly indexed visual lines before the normal ASS reader/audit.

    Each effect layer repeats the same indexed line. Indices, rather than text
    deduplication, preserve repeated words and repeated complete lines.
    """
    if 'Script generated by VideoCaptioner' not in ass or 'VCLineV1:' not in ass:
        return ass
    rows = ass.splitlines()
    groups = {}
    slots = {}
    for number, row in enumerate(rows):
        if not row.startswith('Dialogue: '):
            continue
        fields = row.split(',', 9)
        if len(fields) != 10:
            continue
        match = EVENT.fullmatch(fields[8])
        if not match:
            continue
        index, count = int(match[1]), int(match[2])
        if count < 1 or count > 128 or index >= count:
            raise ValueError('字幕分行回读索引无效')
        key = tuple(fields[1:4])
        group = groups.setdefault(key, {'count': count, 'lines': {}, 'fields': fields, 'first': number})
        if group['count'] != count:
            raise ValueError('字幕分行回读行数不一致')
        clean = re.sub(r'\{[^}]*\}', '', fields[9])
        if index in group['lines'] and group['lines'][index] != clean:
            raise ValueError('字幕分行回读特效层文字不一致')
        group['lines'][index] = clean
        slots[number] = key
    for group in groups.values():
        if set(group['lines']) != set(range(group['count'])):
            raise ValueError('字幕分行回读缺少显示行，未丢弃文字')
    output = []
    for number, row in enumerate(rows):
        if number not in slots:
            output.append(row)
            continue
        group = groups[slots[number]]
        if number == group['first']:
            fields = group['fields'][:]
            fields[0] = 'Dialogue: 0'
            fields[8] = ''
            fields[9] = r'\N'.join(group['lines'][i] for i in range(group['count']))
            output.append(','.join(fields))
    return '\n'.join(output) + ('\n' if ass.endswith('\n') else '')
